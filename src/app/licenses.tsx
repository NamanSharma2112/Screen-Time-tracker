import { router } from 'expo-router';
import { useMemo, useState } from 'react';
import { FlatList, StyleSheet, TextInput, View } from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';

import { BottomSheet } from '@/components/BottomSheet';
import { ListRow } from '@/components/ListRow';
import { ScreenHeader } from '@/components/ScreenHeader';
import { Divider } from '@/components/Surfaces';
import { Txt } from '@/components/Txt';
import { useTheme } from '@/theme/useTheme';

type Pkg = { name: string; version: string; license: string; textId: number | null };
const data: { packages: Pkg[]; texts: string[] } = require('@/legal/licenses.json');

/** Attribution for every open-source package bundled in the app (generated by `npm run legal:licenses`). */
export default function LicensesScreen() {
  const insets = useSafeAreaInsets();
  const { colors, accent } = useTheme();
  const [query, setQuery] = useState('');
  const [open, setOpen] = useState<Pkg | null>(null);
  const items = useMemo(
    () => data.packages.filter((p) => !query || p.name.toLowerCase().includes(query.toLowerCase())),
    [query],
  );

  return (
    <View style={{ flex: 1, backgroundColor: colors.bg, paddingTop: insets.top }}>
      <ScreenHeader
        title="Open-source licences"
        left={{ icon: 'arrow-back', label: 'Back', onPress: () => router.back() }}
      />
      <View style={[styles.search, { backgroundColor: colors.card }]}>
        <TextInput
          value={query}
          onChangeText={setQuery}
          placeholder={`Search ${data.packages.length} packages`}
          placeholderTextColor={colors.textTertiary}
          selectionColor={accent}
          style={[styles.input, { color: colors.text }]}
          accessibilityLabel="Search packages"
        />
      </View>
      <FlatList
        data={items}
        keyExtractor={(p) => `${p.name}@${p.version}`}
        contentContainerStyle={[styles.list, { backgroundColor: colors.sheet, paddingBottom: insets.bottom + 24 }]}
        ItemSeparatorComponent={() => <Divider inset={16} />}
        initialNumToRender={20}
        renderItem={({ item }) => (
          <ListRow label={`${item.name} ${item.version}`} value={item.license} onPress={() => setOpen(item)} />
        )}
        ListHeaderComponent={
          <Txt variant="footnote" tone="secondary" style={styles.header}>
            This app is built with open-source software. Thank you to everyone who made it.
          </Txt>
        }
      />
      <BottomSheet
        visible={!!open}
        draggable={false}
        onClose={() => setOpen(null)}
        title={open ? `${open.name} ${open.version}` : ''}
      >
        <View style={[styles.textBox, { backgroundColor: colors.card }]}>
          <FlatList
            data={[open?.textId != null ? data.texts[open.textId] : `Licensed under ${open?.license ?? ''}.`]}
            keyExtractor={(_, i) => String(i)}
            renderItem={({ item }) => (
              <Txt variant="caption" tone="secondary" selectable>
                {item}
              </Txt>
            )}
          />
        </View>
      </BottomSheet>
    </View>
  );
}

const styles = StyleSheet.create({
  search: { marginHorizontal: 16, borderRadius: 14, paddingHorizontal: 14, marginBottom: 12 },
  input: { height: 44, fontSize: 16 },
  list: { borderTopLeftRadius: 32, borderTopRightRadius: 32, paddingTop: 8, flexGrow: 1 },
  header: { paddingHorizontal: 16, paddingVertical: 12 },
  textBox: { borderRadius: 18, padding: 16, maxHeight: 420 },
});
